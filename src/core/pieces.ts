/**
 * 指定した回転状態のセル座標を返す。
 * 並び順は固定であり、ActivePiece.eventCellIndex はこの並びの添字を指す。
 */
export function getShape(type: MinoType, rot: Rotation): readonly Coord[] {
  const states = SHAPES[type];
  const cells = states[rot];
  // rot は 0-3 に限定された型なので実際には undefined にならない
  return cells ?? states[0] ?? [];
}

/** スポーン時の左上座標。盤面上部のバッファ行に出現させる */
export function getSpawnPosition(type: MinoType): { x: number; y: number } {
  // I と O は4x4/3x3の箱の中心が異なるため個別に調整する
  if (type === 'I') return { x: 3, y: -1 };
  if (type === 'O') return { x: 3, y: 0 };
  return { x: 3, y: 0 };
}


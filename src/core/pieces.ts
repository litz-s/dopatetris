/**
 * 回転時に試行するオフセット列を返す。先頭から順に試し、最初に置けた位置を採用する。
 * O ミノは回転しても形が変わらないため中心のみ。
 */
export function getKicks(type: MinoType, from: Rotation, to: Rotation): readonly Coord[] {
  if (type === 'O') return [[0, 0]];
  const key = `${from}>>${to}` as KickKey;
  const table = type === 'I' ? KICKS_I : KICKS_JLSTZ;
  return table[key];
}

/** 右回転（時計回り）後の回転状態 */
export function rotateCw(rot: Rotation): Rotation {
  return ((rot + 1) % 4) as Rotation;
}

/** 左回転（反時計回り）後の回転状態 */
export function rotateCcw(rot: Rotation): Rotation {
  return ((rot + 3) % 4) as Rotation;
}
